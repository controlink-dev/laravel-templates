<?php

namespace Controlink\Templates\Tests\Feature;

use Controlink\Templates\Contracts\MoneyFormatter;
use Controlink\Templates\Output\Pdf\DocumentComposer;
use Controlink\Templates\Output\Pdf\PdfRenderer;
use Controlink\Templates\Output\Pdf\RenderedPdf;
use Controlink\Templates\Tests\TestCase;
use Controlink\Templates\Types\TemplateType;
use Illuminate\Support\Facades\Http;
use Symfony\Component\Process\ExecutableFinder;

/**
 * Visual regression of the rendered document (RNF-05).
 *
 * This is the only test in the module that needs the real PDF engine (plus poppler, to
 * rasterise what it produced), and it skips itself when either is missing — a developer
 * without a container running, or without poppler-utils installed, should not be
 * blocked, and a machine with both gets the check.
 *
 * Everything except the rendering is frozen in `visual-layout.json`: the layout, the
 * dataset, the document type. If the test composed from the live catalogue instead, a
 * change to a document type would change the picture and the test would fail for
 * reasons that have nothing to do with rendering. What it exists to catch is the shared
 * stylesheet, the compositor or the engine drifting — so everything else is nailed down.
 *
 * `visual-layout.json` was frozen from the host in its own (pre-extraction) config
 * shape — flat `margins`/`max_pages`/`visibility_limits` rather than the package's
 * nested `pdf` array. It is a frozen fixture and is never regenerated by this task, so
 * the mapping into `TemplateType::fromConfig()`'s shape happens here, in the test.
 *
 * The comparison is tolerant, not exact. Renders of the same document are byte
 * identical, but an engine update legitimately shifts antialiasing by a hair, and a
 * test that fails on that gets disabled rather than read. The references are 240px wide
 * for the same reason: block positions and text masses survive the downscale,
 * individual glyph edges do not.
 */
class VisualRegressionTest extends TestCase
{
    /** Mean absolute difference per pixel, on a 0-255 scale. */
    private const TOLERANCE = 6.0;

    protected function setUp(): void
    {
        parent::setUp();

        $finder = new ExecutableFinder;

        foreach (['pdfinfo', 'pdftotext', 'pdftoppm'] as $tool) {
            if (! $finder->find($tool)) {
                $this->markTestSkipped('poppler-utils not installed');
            }
        }
    }

    private function fixture(string $name): string
    {
        return __DIR__.'/../Fixtures/pdf/'.$name;
    }

    public function test_the_rendered_document_still_looks_the_same(): void
    {
        if (! extension_loaded('gd')) {
            $this->markTestSkipped('The gd extension is required to compare rasters.');
        }

        $frozen = json_decode((string) file_get_contents($this->fixture('visual-layout.json')), true);

        $this->assertIsArray($frozen, 'The frozen layout fixture is missing or unreadable.');

        // The engine has to be the real one: a faked response would compare a
        // placeholder against the reference and pass for the wrong reason.
        // allowStrayRequests(), not preventStrayRequests(false): under the test
        // harness the latter leaves the client in fake-recording mode, so a real
        // request throws "without a matching fake" and this test silently skipped.
        Http::allowStrayRequests();

        if (! $this->engineIsReachable()) {
            $this->markTestSkipped('The PDF engine is not reachable at '.config('templates.pdf.gotenberg.url').'.');
        }

        // The money formatter asks the licence for its main currency in the host, and
        // this test has no tenant. The reference was frozen with the same stand-in, so
        // the comparison stays honest. Signature matches this package's contract, which
        // carries no `$decimals` parameter.
        $this->app->instance(MoneyFormatter::class, new class implements MoneyFormatter
        {
            public function format(float|string|null $value): string
            {
                return number_format((float) $value, 2, ',', ' ').' €';
            }
        });

        $type = $this->frozenType($frozen['document_type']);

        $document = app(DocumentComposer::class)->compose(
            $frozen['html'],
            $frozen['css'],
            $type,
            $frozen['dataset'],
        );

        $rendered = app(PdfRenderer::class)->render($document, $type);

        RenderedPdf::open($rendered['pdf'], function (RenderedPdf $pdf): void {
            $pages = $pdf->pageCount();

            $this->assertSame(3, $pages, 'The frozen layout no longer produces three pages.');

            for ($page = 1; $page <= $pages; $page++) {
                $reference = $this->fixture("visual-reference-{$page}.png");

                $this->assertFileExists($reference, "Missing reference for page {$page}.");

                $difference = $this->meanDifference(
                    $pdf->rasterOf($page, 50),
                    (string) file_get_contents($reference),
                );

                $this->assertLessThanOrEqual(
                    self::TOLERANCE,
                    $difference,
                    "Page {$page} drifted from its reference by {$difference} levels per pixel. "
                    .'If the change is intended, regenerate the references and say what changed.',
                );
            }
        });
    }

    /**
     * Maps the host's frozen (pre-extraction) document type shape into this package's
     * `TemplateType::fromConfig()` shape. Never touches the frozen fixture itself.
     *
     * @param  array<string, mixed>  $hostType
     */
    private function frozenType(array $hostType): TemplateType
    {
        return TemplateType::fromConfig('invoice', [
            'label'           => $hostType['label'] ?? 'invoice',
            'output'          => 'pdf',
            'bindings'        => $hostType['bindings'] ?? [],
            'fixture'         => $hostType['fixture'] ?? [],
            'fixture_repeats' => $hostType['fixture_line_repeats'] ?? 1,
            'initial_layout'  => $hostType['initial_layout'] ?? [],
            'pdf'             => [
                'paper_format'       => $hostType['paper_format'] ?? 'A4',
                'margins'            => $hostType['margins'] ?? [],
                'visibility_limits'  => $hostType['visibility_limits'] ?? [],
                'line_row_height_mm' => $hostType['line_row_height_mm'] ?? 4.5,
                'max_pages'          => $hostType['max_pages'] ?? 10,
            ],
        ]);
    }

    /**
     * Mean absolute difference per pixel, after scaling the fresh render down to the
     * reference's size.
     */
    private function meanDifference(string $freshPng, string $referencePng): float
    {
        $fresh     = imagecreatefromstring($freshPng);
        $reference = imagecreatefromstring($referencePng);

        $this->assertNotFalse($fresh, 'The fresh render could not be read as an image.');
        $this->assertNotFalse($reference, 'The reference could not be read as an image.');

        // Both come out of poppler as 8-bit greyscale, which GD treats as a palette
        // image: `imagecolorat` would hand back a palette index rather than a level, and
        // comparing an index against a level reports almost every pixel as different.
        imagepalettetotruecolor($fresh);
        imagepalettetotruecolor($reference);

        $width  = imagesx($reference);
        $height = imagesy($reference);

        $scaled = imagescale($fresh, $width, $height);
        imagedestroy($fresh);

        $this->assertNotFalse($scaled, 'The fresh render could not be scaled for comparison.');

        $total = 0;

        for ($y = 0; $y < $height; $y++) {
            for ($x = 0; $x < $width; $x++) {
                // Grey, so any channel is the value; red is as good as any.
                $total += abs(
                    (imagecolorat($scaled, $x, $y) >> 16 & 0xFF)
                    - (imagecolorat($reference, $x, $y) >> 16 & 0xFF)
                );
            }
        }

        imagedestroy($scaled);
        imagedestroy($reference);

        return round($total / ($width * $height), 3);
    }

    private function engineIsReachable(): bool
    {
        try {
            return Http::timeout(3)
                ->get(rtrim((string) config('templates.pdf.gotenberg.url'), '/').'/health')
                ->successful();
        } catch (\Throwable) {
            return false;
        }
    }
}
